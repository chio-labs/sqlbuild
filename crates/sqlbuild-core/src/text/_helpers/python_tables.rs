/// Whether `character` falls in one of the sorted inclusive `ranges`.
pub(crate) fn in_ranges(ranges: &[(u32, u32)], character: char) -> bool {
    let code: u32 = u32::from(character);
    let index: usize = ranges.partition_point(|(_, end)| *end < code);
    ranges.get(index).is_some_and(|(start, _)| *start <= code)
}
