//! The terminal cells one character occupies.

/// The terminal cells one character occupies: zero for combining marks, two for wide characters.
#[must_use]
pub fn char_cells(character: char) -> usize {
    let code: u32 = u32::from(character);
    let zero_width: bool = matches!(
        code,
        0x0300..=0x036F | 0x200B..=0x200F | 0x20D0..=0x20FF | 0xFE00..=0xFE0F | 0xFE20..=0xFE2F
    );
    let wide: bool = matches!(
        code,
        0x1100..=0x115F
            | 0x2E80..=0x303E
            | 0x3041..=0x33FF
            | 0x3400..=0x4DBF
            | 0x4E00..=0x9FFF
            | 0xA000..=0xA4CF
            | 0xAC00..=0xD7A3
            | 0xF900..=0xFAFF
            | 0xFE30..=0xFE4F
            | 0xFF00..=0xFF60
            | 0xFFE0..=0xFFE6
            | 0x1F300..=0x1F64F
            | 0x1F900..=0x1F9FF
            | 0x20000..=0x3FFFD
    );
    if zero_width {
        0
    } else if wide {
        2
    } else {
        1
    }
}
